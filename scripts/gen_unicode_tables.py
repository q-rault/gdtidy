"""Generate crates/gdsyntax/src/lexer/unicode.rs from a Godot checkout.

Godot decides which characters may start or continue an identifier with
tables generated from the Unicode database (core/string/char_range.cpp).
Copying them keeps gdsyntax's identifiers exactly in step with Godot's.

    python scripts/gen_unicode_tables.py <path-to-godot> <git-tag>
"""
import re
import subprocess
import sys
from pathlib import Path

godot, tag = sys.argv[1], sys.argv[2]
source = subprocess.run(
    ["git", "-C", godot, "show", f"{tag}:core/string/char_range.cpp"],
    check=True, capture_output=True, text=True,
).stdout
unicode_version = re.search(r"Public/([0-9.]+)/ucd", source).group(1)


def table(name):
    body = re.search(name + r"\[[^\]]*\] = \{(.*?)\};", source, re.S).group(1)
    return re.findall(r"\{ (0x[0-9a-f]+), (0x[0-9a-f]+) \}", body)


out = [
    "// Generated by scripts/gen_unicode_tables.py from Godot "
    f"{tag} (Unicode {unicode_version}). Do not edit.",
    "",
]
for rust, cpp in (("XID_START", "xid_start"), ("XID_CONTINUE", "xid_continue")):
    ranges = table(cpp)
    out.append(f"pub(super) static {rust}: [(u32, u32); {len(ranges)}] = [")
    out += [f"    ({a}, {b})," for a, b in ranges]
    out.append("];")
    out.append("")
target = Path(__file__).resolve().parent.parent / "crates/gdsyntax/src/lexer/unicode.rs"
target.write_text("\n".join(out), encoding="utf-8", newline="\n")
print(f"wrote {target} from Godot {tag}, Unicode {unicode_version}")
